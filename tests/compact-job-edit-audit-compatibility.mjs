import assert from 'node:assert/strict';
import {reconcileCompactJobEditAudit as reconcile} from '../supabase/functions/workshop-api/extensions/compact_job_edit_audit.js';
const a={job:'JC1',at:1},b={job:'JC2',at:2},c={job:'JC3',at:3},d={job:'JC4',at:4},e={job:'JC5',at:5};
const marker={snapshotRevision:100,prefixCount:2};
const current={jobEditArchive:marker,jobEdits:[c,d]};
const expandedCurrent=[a,b,c,d];
const legacy=(base,proposed,expanded=expandedCurrent)=>reconcile({base:{jobEdits:base},current,proposed:{jobEdits:proposed},expandedCurrent:expanded});
assert.deepEqual(legacy([a,b,c],[a,b,c,e]).jobEdits,[c,d,e]);
assert.deepEqual(legacy([a,b,c],[e,a,b,c]).jobEdits,[c,d,e]);
assert.deepEqual(legacy([a],[a,e]).jobEdits,[c,d,e]);
assert.deepEqual(legacy([a,b,c],[{at:1,job:'JC1'},b,c]).jobEdits,[c,d]);
assert.equal(legacy([a,b,c],[a,c,e]).code,'audit_refresh_required');
assert.equal(legacy([a,b,c],[a,b,c,d]).code,'audit_replay_ambiguous');
assert.equal(legacy([a,b,c],[a,b,c,e],[a,b,c,e]).code,'audit_history_unavailable');
assert.deepEqual(legacy([a,b,c],[a,b,c,e,e]).jobEdits,[c,d,e,e]);
assert.deepEqual(legacy([a,b,c],[c,b,a,e]).jobEdits,[c,d,e]);
const compact=(base,proposed)=>reconcile({base:{jobEditArchive:marker,jobEdits:base},current,proposed});
assert.deepEqual(compact([c],{jobEditArchive:marker,jobEdits:[e,c]}).jobEdits,[c,d,e]);
assert.equal(compact([c],{jobEdits:[c,e]}).code,'audit_refresh_required');
assert.equal(compact([c],{jobEditArchive:{...marker,prefixCount:3},jobEdits:[c,e]}).code,'audit_refresh_required');
assert.equal(compact([c],{jobEditArchive:marker,jobEdits:[d,c]}).code,'audit_replay_ambiguous');
assert.equal(reconcile({base:{jobEdits:[a]},current:{jobEdits:[a]},proposed:{jobEdits:[a,b]}}).active,false);
assert.deepEqual(current.jobEdits,[c,d]);
console.log('15 compact legacy audit compatibility assertions passed');
