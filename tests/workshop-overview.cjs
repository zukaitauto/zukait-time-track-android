assert.equal(api.search(jobs,'not-found').length,0);
assert.equal(api.unassigned([{no:'JC01'}],[{job:'jc01'}]).length,0);
assert.equal(api.unassigned([{no:'JC01'}],[{job:'JC01',cancelled:true}]).length,1);
