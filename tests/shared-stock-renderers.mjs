import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const env={window:{}};
runInNewContext(readFileSync('app/src/main/assets/consumables_stock_core.js','utf8'),env);
env.window.ZukaitStockCore=env.ZukaitStockCore;
runInNewContext(readFileSync('app/src/main/assets/consumables_stock_ui.js','utf8'),env);
const w=env.window,c=w.ZukaitStockCore;
assert.equal((w.zukaitSharedStockMenu().html.match(/data-as=/g)||[]).length,6);
for(const scope of ['Painting','Mechanical'])assert.equal((w.zukaitSharedStockMenu({scope}).html.match(/data-as=/g)||[]).length,4);
const pair={materialId:'m',brandId:'b',material:'Primer',brand:'Brand',unit:'Liter'};
assert.match(w.zukaitSharedStockWrite({page:'opening',pairs:[pair],hasMore:true}).html,/data-as="opening-pair:0"/);
assert.match(w.zukaitSharedStockWrite({page:'opening'}).html,/No linked material/);
assert.match(w.zukaitSharedStockWrite({page:'adjust',pairs:[pair]}).html,/data-as="save-adjust"/);
assert.match(w.zukaitSharedStockRead({page:'balance',rows:[{material_id:'m',brand_id:'b',unit:'Liter',initialised:true,physical:2,reserved:1,stock_value:4,minimum:1}]}).html,/data-as="balance-detail:0"/);
assert.match(w.zukaitSharedStockRead({page:'history',rows:[{id:1,material_id:'m',brand_id:'b',actor_id:'A1'}],hasMore:true,moreAction:'history:1'}).html,/Staff A1/);
assert.match(w.zukaitSharedStockRead({page:'reports',report:{valuation:12}}).html,/12\.000 OMR/);
assert.doesNotMatch(w.zukaitSharedStockRead({page:'reports',report:{valuation:null}}).html,/0\.000 OMR/);
assert.match(c.purchaseEntryMarkup({invoiceNumber:'"><script>',supplier:'A',invoiceDate:'2026-11-25'},'2026-11-25'),/&lt;script&gt;/);
assert.match(c.masterPriceFields('2026-11-25'),/cmDate/);
assert.match(c.masterCreateMarkup(),/value="Both"/);
console.log('PASS shared Stock renderer smoke checks');
