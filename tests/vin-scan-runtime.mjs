import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync('app/src/main/assets/vin_scan.js','utf8');
const vin='1HGCM82633A004352';
function setup(){
 const field={value:'',events:[],focus(){},dispatchEvent(e){this.events.push(e.type)}};
 const ctx={alerts:[],confirms:[],captures:0,state:{jobs:[]},document:{getElementById:id=>id==='vin'?field:null},Event:class{constructor(type){this.type=type}}};
 ctx.alert=m=>ctx.alerts.push(m);ctx.window={confirm:m=>{ctx.confirms.push(m);return true},AndroidBridge:{scanVinBarcode(){},captureVinPhoto(){ctx.captures++}}};
 vm.runInNewContext(source,ctx);ctx.scan=ctx.window.zukaitVinScan;ctx.field=field;return ctx;
}
const parser=setup().scan;
assert.equal(parser.candidate('VIN: '+vin),vin);
assert.equal(parser.candidate('CHASSIS: 1HG CM826 33A004352'),vin);
assert.equal(parser.candidate('Model 2025\n1HGCM8263\n3A004352'),'','Never join unrelated OCR lines');
assert.equal(parser.candidate('AA'+vin+'BB'),'','Never take a 17-character window from a longer barcode');
assert.equal(parser.candidate('VIN OCR\n1HGCM82633A00435O'),'1HGCM82633A004350');
assert.equal(parser.vinCheckDigit(vin),true);
const international=setup();international.scan.capture('vin');
international.scan.nativeResult('WVWZZZ1JZXW000001','','PHOTO');
assert.equal(international.captures,1,'Check digit warning does not reopen the camera');
assert.equal(international.field.value,'WVWZZZ1JZXW000001');
const corrected=setup();corrected.scan.capture('vin');
corrected.scan.nativeResult('1HGCM82633A00435O','','PHOTO');
assert.equal(corrected.captures,2,'One verification capture for OCR correction');
assert.equal(corrected.field.value,'');
corrected.scan.nativeResult('1HGCM82633A00435O','','PHOTO');
assert.equal(corrected.captures,2,'Matching verification completes without another capture');
assert.equal(corrected.field.value,'1HGCM82633A004350');
assert.deepEqual(corrected.field.events,['input','change']);
const disagreement=setup();disagreement.scan.capture('vin');
disagreement.scan.nativeResult('1HGCM82633A00435O','','PHOTO');
disagreement.scan.nativeResult(vin,'','PHOTO');
assert.equal(disagreement.captures,2);
assert.equal(disagreement.field.value,'','Different second capture must not overwrite field');
assert.match(disagreement.alerts.at(-1),/do not match/);
const cancelled=setup();cancelled.scan.capture('vin');
cancelled.scan.nativeResult('1HGCM82633A00435O','','PHOTO');
cancelled.scan.nativeResult('','cancelled','PHOTO');
cancelled.scan.capture('vin');cancelled.scan.nativeResult('1HGCM82633A00435O','','PHOTO');
assert.equal(cancelled.captures,4,'Cancelled verification resets before a fresh attempt');
const unavailable=setup();unavailable.scan.open('vin');unavailable.scan.nativeResult('','scanner_unavailable','BARCODE');
assert.match(unavailable.alerts.at(-1),/Google Play services/);
assert.equal(unavailable.field.value,'');
const rejected=setup();rejected.window.confirm=()=>false;rejected.scan.open('vin');rejected.scan.nativeResult(vin,'','BARCODE');
assert.equal(rejected.field.value,'','User review cancellation preserves field');
const native=fs.readFileSync('app/src/main/java/com/zukait/timetrack/MainActivity.java','utf8');
assert.match(native,/intent\.setClipData\(android\.content\.ClipData\.newRawUri\("VIN photo", uri\)\)/);
assert.doesNotMatch(native,/pendingVinCaptureFile\.deleteOnExit/);
assert.match(native,/addOnCompleteListener\(task -> \{\s*recognizer\.close\(\);\s*if \(captureFile != null\) captureFile\.delete\(\);/);
assert.match(fs.readFileSync('app/src/main/AndroidManifest.xml','utf8'),/com\.google\.mlkit\.vision\.DEPENDENCIES[\s\S]*?barcode_ui/);
console.log('PASS: VIN extraction, international VINs, bounded OCR verification, disagreement, cancellation, review and scanner fallback.');
