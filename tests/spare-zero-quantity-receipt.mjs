import fs from 'node:fs';
import assert from 'node:assert/strict';
// Reuse the real UI/API fixture rather than duplicating receipt or projection rules.
const suite=fs.readFileSync('tests/v215-spare-parts-entry-regression.mjs','utf8');
const prefix=suite.slice(0,suite.indexOf('\ntest('));
assert.ok(prefix.length>1000&&prefix.length<suite.length);
const {fixture}=await import('data:text/javascript;base64,'+Buffer.from(prefix+'\nexport {fixture};').toString('base64'));
const f=fixture('Manager','M1');
const rows=f.serverRows;
rows.splice(2);
rows.push({event_id:'manager-arrived-without-qty',entity_id:f.partId,actor_id:'M1',event_type:'SPARE_PART_MANAGER_CORRECTED',revision:2,server_time:'2026-10-20T08:00:00Z',payload:{partId:f.partId,listNo:f.listNo,jobCard:f.jobCard,reason:'Physically arrived',after:{name:'Head lamp RH',qty:1,status:'RECEIVED',purchaseAmount:0}}});
f.parts.hydrateFromServerRows(rows);
let item=f.lists()[0].items[0];
assert.equal(item.status,'RECEIVED');assert.equal(Number(item.receivedQty||0),0);
assert.equal(f.parts.arrivalPendingCount(f.lists()),0);
assert.equal(f.parts.nextActionFor(item,'Manager')[1],'RECEIVED');
assert.equal(f.parts.nextActionFor(item,'Purchaser')[1],'RECEIVED');
assert.equal(f.parts.nextActionFor(item,'Supervisor'),null,'zero quantity cannot be verified');
f.window.prompt=()=>null;await f.parts.quickAdvance(f.listNo,f.partId,'RECEIVED');assert.equal(f.commits.length,0);
f.window.prompt=()=> '2';await f.parts.quickAdvance(f.listNo,f.partId,'RECEIVED');assert.equal(f.commits.length,0,'cannot over-receive');
f.window.prompt=()=> '1';await f.parts.quickAdvance(f.listNo,f.partId,'RECEIVED');
assert.equal(f.commits.length,1);assert.equal(f.commits[0].payload.receivedQty,1);assert.equal(f.commits[0].payload.from,'RECEIVED');assert.equal(f.commits[0].payload.to,'RECEIVED');
await f.parts.hydrateAuthoritativeLists();item=f.lists()[0].items[0];assert.equal(item.receivedQty,1);
assert.equal(f.parts.arrivalPendingCount(f.lists()),1);
assert.equal(f.parts.nextActionFor(item,'Supervisor')[1],'SUPERVISOR_VERIFIED');
await f.parts.openInvoiceEntry();assert.doesNotMatch(f.html(),/v2-sp-invoice-index/,'receipt still needs confirmation before invoice entry');
await f.parts.confirmArrival({dataset:{list:f.listNo,item:f.partId},disabled:false});
await f.parts.openInvoiceEntry();assert.match(f.html(),/v2-sp-invoice-index/,'confirmed receipt now appears for invoicing');
const p=fixture('Purchaser','P1',JSON.parse(JSON.stringify(rows.slice(0,3))));
const partial={...item,qty:3,receivedQty:1,status:'RECEIVED'};
assert.equal(p.parts.nextActionFor(partial,'Purchaser')[1],'RECEIVED','partial receipts can record remaining quantity');
console.log('PASS: manager-corrected zero-quantity receipt recovery, quantity validation, role checks and confirmation-before-invoice flow.');
