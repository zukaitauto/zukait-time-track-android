import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const C=require('../app/src/main/assets/consumables.js');
const manager={id:'MGR',role:'Manager'};
const state={};
const add=(name,department,category='Consumable')=>
 C.addMaterial(state,{name,department,unit:'Liter',category},manager);
const paint=add('Primer','Painting','Paint');
const mechanical=add('Engine Oil','Mechanical');
const shared=add('Cleaning Solvent','Both');
assert.equal(paint.department,'Painting');
assert.equal(mechanical.department,'Mechanical');
assert.equal(shared.department,'Both');
assert.throws(()=>add('Invalid paint','Both','Paint'),/PAINT_ONLY_MATERIAL/);
assert.throws(()=>add('Invalid department','Bodyshop'),/INVALID_MATERIAL_DEPARTMENT/);
assert.throws(()=>C.addMaterial(state,{name:'Duplicate',unit:'Liter',department:'Mechanical'}, {role:'Supervisor'}),/MANAGER_ONLY/);
const brand=C.addBrand(state,{name:'Brand A'},manager);
assert.throws(()=>C.issue(state,{jobCard:'JC1',lines:[{materialId:mechanical.id,brandId:brand.id,quantity:1}]},manager),/MATERIAL_DEPARTMENT_FORBIDDEN/);
assert.doesNotThrow(()=>C.issue(state,{jobCard:'JC2',lines:[{materialId:shared.id,brandId:brand.id,quantity:1}]},manager));
const legacy=C.addMaterial(state,{name:'Legacy Bodyshop Material',unit:'Piece',category:'Consumable'},manager);
assert.equal(legacy.department,'Unassigned','Do not silently rewrite saved legacy records');
const ui=readFileSync('app/src/main/assets/consumables_stock_ui.js','utf8');
const master=readFileSync('app/src/main/assets/consumables_ui.js','utf8');
assert.match(ui,/const stockMaterialDepartment=m=>.*:'Painting';/,'Legacy material display should default to Paint');
assert.match(ui,/stockMaterialInDepartment\(x\)/,'Department menus must filter material choices');
assert.match(ui,/Materials &amp; Brands/,'Stock menu must expose Materials & Brands');
assert.match(ui,/zs-manager-actions\{display:grid;grid-template-columns:repeat\(2,minmax\(0,1fr\)\)/,'Stock management actions must have two columns');
assert.match(master,/modal\('Materials & Brands'/,'Manager page title must use new name');
assert.doesNotMatch(master,/action\('Brands & Price'/,'Old Painting menu must not retain the master action');
assert.match(master,/cmNewDepartment/,'Manager must choose the new material department');
assert.match(master,/r\.m\.department==='Both'\?'Shared'/,'Master must display Shared scope');
console.log('PASS: Materials & Brands in Stock, legacy Paint display, Mechanical isolation, Shared inventory scope, Manager-only creation');
