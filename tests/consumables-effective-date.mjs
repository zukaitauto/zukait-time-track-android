import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const C=createRequire(import.meta.url)('../app/src/main/assets/consumables.js');
const s={sessions:[{id:'existing-work'}],assign:[{id:'existing-assignment'}]};
const mgr={id:'MGR001',role:'Manager'};
const m=C.addMaterial(s,{name:'Disc 1500',unit:'Piece'},mgr);
const b=C.addBrand(s,{name:'Brand'},mgr);
const p=C.setPrice(s,{materialId:m.id,brandId:b.id,pricePerUnit:3,effectiveFrom:2000,reason:'Initial'},mgr);
const later=C.setPrice(s,{materialId:m.id,brandId:b.id,pricePerUnit:2,effectiveFrom:4000,reason:'Later period'},mgr);
const row=(id,at,priceId,unitPrice)=>({id,jobCard:id,locked:true,actualAt:at,lines:[{materialId:m.id,brandId:b.id,actualQuantity:1,priceId,unitPriceSnapshot:unitPrice,lineCost:unitPrice},{materialId:'other',brandId:b.id,actualQuantity:1,lineCost:14.215}],totalCost:14.215+unitPrice});
s.consumables.actuals.push(row('before',1999,p.id,3),row('12003',2000,p.id,3),row('later',4000,later.id,2),{...row('voided',3000,p.id,3),voided:true});
const fingerprint=C.timeControlFingerprint(s);
C.managerCorrectPrice(s,p.id,1.7,mgr,'Wrong price');
assert.equal(s.consumables.actuals[0].totalCost,17.215,'before effective date remains unchanged');
assert.equal(s.consumables.actuals[1].totalCost,15.915,'effective date is inclusive');
assert.equal(s.consumables.actuals[1].lines[0].lineCost,1.7);
assert.equal(s.consumables.actuals[2].totalCost,16.215,'later period remains applicable');
assert.equal(s.consumables.actuals[3].totalCost,17.215,'voided rows remain untouched');
assert.equal(C.timeControlFingerprint(s),fingerprint);
assert.equal(C.managerRecalculateActualPrices(s,p.id,mgr,'Retry').length,0);
console.log('Effective-date price correction regression passed');
