import fs from 'node:fs';import assert from 'node:assert/strict';
const s=fs.readFileSync('app/src/main/assets/v74_updates.js','utf8');
const start=s.indexOf('V123 MANAGER WORKSHOP PERFORMANCE');
const end=s.indexOf('V106 ID001 FINAL AUTHORITY',start);
assert.ok(start>=0&&end>start,'Manager Workshop Performance block must exist');
const b=s.slice(start,end);
assert.match(b,/v124-liquid \.v123-grid\{grid-template-columns:repeat\(3,minmax\(0,1fr\)\)!important/,'Workshop Performance must stay three-column including mobile');
assert.match(b,/backdrop-filter:blur\(12px\)/,'performance cards must use liquid-glass treatment');
assert.match(b,/v124OpenTotalPurchase/,'Total Purchase card must exist');
assert.match(b,/v124OpenConsumablesExpense/,'Consumables Expense must remain a separate card');
assert.match(b,/const price=Number\(p\.finalPrice\)/,'Total Purchase must use confirmed final Spare Parts price');
assert.match(b,/total\+=price\*Math\.max\(1,Number\(p\.qty\)\|\|1\)/,'Total Purchase must multiply final unit price by quantity');
assert.match(b,/No confirmed .*Spare Parts purchases/,'empty purchase drilldown must be explicit');
assert.match(b,/zukaitV2\.sparePartsMain\.openList/,'clicking a purchase JC must open its Parts List');
assert.match(b,/state\.consumables\?\.actuals/,'Consumables Expense must use finalized actual records');
assert.match(b,/!x\.voided&&x\.locked/,'Consumables Expense must exclude voided/unfinalized records');
assert.match(b,/consSelectTotalJC/,'clicking a consumables JC must drill into its consumables detail');
assert.match(b,/Job Card \/ Vehicle/,'purchase drilldown must show Job Card and Vehicle');
assert.equal((b.match(/>Total Purchase</g)||[]).length,1,'Total Purchase must have one dashboard card only');
assert.equal((b.match(/>Consumables Expense</g)||[]).length,1,'Consumables Expense must have one dashboard card only');
console.log('Manager Workshop Performance purchase/consumables regression passed');
