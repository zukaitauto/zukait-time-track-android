import assert from 'node:assert/strict';
import {jobEditWireState,requestArchivePrefixReader} from '../supabase/functions/workshop-api/extensions/job_edit_archive_wire.js';
const a={job:'JC1',at:1},b={job:'JC2',at:2};
const current={jobs:[{no:'JC1'}],jobEditArchive:{snapshotRevision:100,prefixCount:2},jobEdits:[b]};
const original=JSON.stringify(current);
let reads=0;
const reader=requestArchivePrefixReader(async(revision,count)=>{reads++;return {ok:true,snapshotRevision:revision,prefixCount:count,entries:[a,a]};});
const expected={jobs:current.jobs,jobEdits:[a,a,b]};
assert.deepEqual(await jobEditWireState(current,false,reader),expected);
assert.deepEqual(await jobEditWireState(current,false,reader),expected);
assert.equal(reads,1);
assert.equal(JSON.stringify(current),original);
assert.equal(await jobEditWireState(current,true,reader),current);
assert.equal(reads,1);
assert.equal(await jobEditWireState(expected,false,reader),expected);
assert.equal(await jobEditWireState(null,false,reader),null);
await assert.rejects(jobEditWireState({...current,jobEditArchive:null},false,reader),/audit_history_unavailable/);
await assert.rejects(jobEditWireState(current,false,async()=>({ok:false})),/audit_history_unavailable/);
await assert.rejects(jobEditWireState(current,false,async()=>({ok:true,snapshotRevision:100,prefixCount:2,entries:[a]})),/audit_history_unavailable/);
await assert.rejects(jobEditWireState(current,false,async()=>({ok:true,snapshotRevision:101,prefixCount:2,entries:[a,a]})),/audit_history_unavailable/);
console.log('12 wire compatibility assertions passed');
